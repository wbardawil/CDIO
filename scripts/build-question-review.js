// Produces docs/QUESTION-REVIEW.md — a human-scannable digest of the rebuilt
// 128 question→citation bank. Reads diagnostic-questions.ts + question-
// citations.ts + ratified-modules.json (no deps, no build step).
// Run: node scripts/build-question-review.js
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const QUESTIONS = path.join(ROOT, "src", "lib", "playbook", "diagnostic-questions.ts");
const CITATIONS = path.join(ROOT, "src", "lib", "playbook", "question-citations.ts");
const RATIFIED = path.join(ROOT, "scripts", "ratified-modules.json");
const OUT = path.join(ROOT, "docs", "QUESTION-REVIEW.md");

const ts = fs.readFileSync(QUESTIONS, "utf-8");
const cs = fs.readFileSync(CITATIONS, "utf-8");
const led = JSON.parse(fs.readFileSync(RATIFIED, "utf-8"));

// parse questions (id, module, subcategory, question text)
const STR = '((?:[^"\\\\]|\\\\.)*)';
const qRe = new RegExp(
  'id:\\s*"' + STR + '"\\s*,\\s*module_number:\\s*(\\d+)\\s*,\\s*subcategory:\\s*"' +
    STR + '"\\s*,\\s*question:\\s*"' + STR + '"',
  "g"
);
const questions = [];
let m;
while ((m = qRe.exec(ts))) {
  questions.push({
    id: JSON.parse('"' + m[1] + '"'),
    module: parseInt(m[2], 10),
    subcategory: JSON.parse('"' + m[3] + '"'),
    question: JSON.parse('"' + m[4] + '"'),
  });
}

// parse module titles from MODULE_NAMES or playbook
const titleRe = /MODULE (\d+):\s+(.+?)\s*\r?\n/g;
const titles = {};
const playbook = fs.readFileSync(
  path.join(ROOT, "source-playbook", "01_ASSESSMENT_FRAMEWORK.md"),
  "utf-8"
);
let t;
while ((t = titleRe.exec(playbook))) titles[parseInt(t[1], 10)] = t[2];

// parse rubric L5 lines for the level_5 text per module
const rubricRe = /(\d+):\s*\{[\s\S]*?l5:\s*"((?:[^"\\]|\\.)*)"\s*,?\s*\}/g;
const rb = ts.match(/const LEVEL_RUBRIC[^=]*=\s*\{([\s\S]*?)\n\};/);
const l5s = {};
if (rb) {
  let r;
  while ((r = rubricRe.exec(rb[1])))
    l5s[parseInt(r[1], 10)] = JSON.parse('"' + r[2] + '"');
}

// parse citations
const entryRe = /"(m\d+_q\d+)"\s*:\s*\{([\s\S]*?)\n\s{2}\},/g;
const sv = (b, k) => {
  const m2 = b.match(new RegExp(k + ':\\s*"' + STR + '"'));
  return m2 ? JSON.parse('"' + m2[1] + '"') : undefined;
};
const bv = (b, k) => new RegExp(k + ':\\s*true').test(b);
const citations = {};
let e;
while ((e = entryRe.exec(cs))) {
  const b = e[2];
  citations[e[1]] = {
    framework: sv(b, "framework"),
    reference: sv(b, "reference"),
    rationale: sv(b, "rationale"),
    grade: (b.match(/grade:\s*"(\w+)"/) || [])[1],
    locator: sv(b, "locator"),
    semanticPass: bv(b, "semanticPass"),
    clientVisible: bv(b, "clientVisible"),
    accessStatus: sv(b, "accessStatus"),
    sourceType: sv(b, "sourceType"),
    confidenceNote: sv(b, "confidenceNote"),
  };
}

const ratified = new Set(led.ratifiedModules || []);
const log = led.ratificationLog || {};

// helpers
const badge = (g) => g === "strong" ? "🟢 **strong**" :
                     g === "weak"   ? "🟡 weak"      :
                                       "🔴 **indefensible**";
const locFmt = (loc) =>
  !loc ? "—" :
  /^https?:\/\//.test(loc) ? `[link](${loc})` :
  "`" + loc.replace(/\|/g, "\\|").slice(0, 80) + (loc.length > 80 ? "…" : "") + "`";

// header + bank-wide stats
let out = "# Question Review — defensibility-bar rebuild (2026-05-19)\n\n";
out += "Generated by `scripts/build-question-review.js`. Source of truth: `src/lib/playbook/question-citations.ts` (committed) + `scripts/ratified-modules.json` (per-module ratification ledger). 128 questions, 16 modules, zero question-wording changes vs the playbook.\n\n";
const tot = { strong: 0, weak: 0, indefensible: 0 };
for (const q of questions) tot[citations[q.id].grade]++;
out += `**Bank totals:** ${tot.strong} strong · ${tot.weak} weak · ${tot.indefensible} indefensible · ${questions.length} total\n\n`;
out += `**Ratified modules:** ${[...ratified].sort((a, b) => a - b).join(", ")} (${ratified.size}/16)\n\n`;
out += "**Legend** — 🟢 strong = maps to a specific named construct (fetch-verified for public sources, precise named-clause for paywalled); 🟡 weak = real construct but loose semantic fit / forward-looking / honest exception flagged; 🔴 indefensible = no named construct (bank now has 0).\n\n";
out += "**How to review:** scan each module; the named-construct + locator should make sense for the question. Flag anything that doesn't and I'll revisit. The ledger's `reviewNote` per module calls out judgment calls.\n\n";

// honest exceptions roll-up
out += "## ⚠️ Honest WEAK exceptions to review (4 — none fabricated; anti-hallucination over-rode all-strong)\n\n";
const exc = questions.filter((q) => citations[q.id].grade === "weak" && citations[q.id].semanticPass === false);
out += "| id | question | why weak | suggested founder action |\n|---|---|---|---|\n";
const suggestedAction = {
  m14_q3: "Reword to '…software-delivery metrics tracked (DORA Four Keys)?' → DORA strong",
  m15_q5: "Reword toward automation-as-solution-within-process-improvement → DMAIC Improve strong",
  m15_q7: "Reword toward GOVERNANCE of AI in automation → NIST AI RMF strong",
  m16_q8: "Reword toward concrete ongoing tech-skill development → COBIT APO07 strong",
};
for (const q of exc) {
  const c = citations[q.id];
  out += `| \`${q.id}\` | ${q.question} | ${c.confidenceNote ? c.confidenceNote.split(". ")[0].slice(0, 140) : ""} | ${suggestedAction[q.id] || "—"} |\n`;
}
out += "\n";

// per-module sections
const byMod = {};
for (const q of questions) (byMod[q.module] ||= []).push(q);
const modOrder = Object.keys(byMod).map(Number).sort((a, b) => a - b);
for (const n of modOrder) {
  const qs = byMod[n];
  out += `\n---\n\n## Module ${n} — ${titles[n] || "(no title)"}\n\n`;
  if (ratified.has(n)) {
    const r = log[String(n)] || {};
    const provenance = (r.ratifiedBy || "").startsWith("AUTONOMOUS")
      ? "🤖 **AUTONOMOUS** (founder 'allow all' authorization — async review pending)"
      : "👤 **founder-ratified** at AskUserQuestion gate";
    out += `**Status:** ${provenance}  \n`;
    if (r.rubricL1to4) out += `**Rubric L1-4 note:** ${r.rubricL1to4}\n\n`;
    if (r.level5) out += `**Level 5:** ${r.level5}\n\n`;
    if (r.reviewNote) out += `**Review note:** ${r.reviewNote}\n\n`;
  } else {
    out += "**Status:** not yet ratified.\n\n";
  }
  // group by subcategory
  const subs = {};
  for (const q of qs) (subs[q.subcategory] ||= []).push(q);
  for (const sub of Object.keys(subs)) {
    out += `### ${sub}\n\n`;
    out += "| id | question | grade | named construct | locator |\n|---|---|---|---|---|\n";
    for (const q of subs[sub]) {
      const c = citations[q.id];
      const qtxt = q.question.replace(/\|/g, "\\|");
      const ref = (c.reference || "").replace(/\|/g, "\\|").slice(0, 180);
      out += `| \`${q.id}\` | ${qtxt} | ${badge(c.grade)} | **${(c.framework || "").replace(/\|/g, "\\|")}** — ${ref} | ${locFmt(c.locator)} |\n`;
    }
    out += "\n";
  }
  // level_5 text
  if (l5s[n]) out += `**Level 5 text (current):** _${l5s[n].replace(/_/g, " ")}_\n\n`;
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
console.log(`Wrote ${OUT} — ${questions.length} questions across ${modOrder.length} modules`);
